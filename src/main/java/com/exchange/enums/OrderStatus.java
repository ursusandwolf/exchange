package com.exchange.enums;

/**
 * Статус ордера в жизненном цикле.
 */
public enum OrderStatus {
    /**
     * Ордер создан и ожидает исполнения.
     */
    PENDING,
    /**
     * Ордер частично исполнен (часть объёма осталась в стакане).
     */
    PARTIALLY_FILLED,
    /**
     * Ордер полностью исполнен.
     */
    FILLED,
    /**
     * Ордер отменён пользователем.
     */
    CANCELLED,
    /**
     * Ордер отклонён (например, недостаточно средств).
     */
    REJECTED
}
